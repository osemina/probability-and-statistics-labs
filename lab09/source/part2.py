 ('p', 'The difference between what actually happened (yᵢ) and what the line predicts (ŷᵢ) is the **residual**, our estimate of the error:'),
 ('eq', r'$$e_i = y_i - \hat{y}_i$$'),
 ('h2', 'The Least Squares Method'),
 ('p', 'Many lines can be drawn through a cloud of points. Which one is the best? We use the **least squares** method: we choose b₀ and b₁ so that the **Sum of Squared Errors (SSE)** is as small as possible:'),
 ('eq', r'$$SSE = \sum_{i=1}^{n} e_i^2 = \sum_{i=1}^{n} (y_i - \hat{y}_i)^2 \rightarrow \min$$'),
 ('p', 'Figure 3 shows the idea: every residual becomes a square with area e², and the least squares line is the line with the smallest total area.'),
 ('figure', 'F3'),
 ('cap', 'Figure 3. Four lines through the same five points. Each gold square has area e² (a squared residual). The flat line has SSE = 320, a steep line has SSE = 64, and the least squares line ŷ = 46.2 + 5.6x has the smallest SSE = 6.4.'),
 ('box', 'tip', '**Why squares?** If we simply added the residuals, the positive and the negative ones would cancel out, and many bad lines would have a total of 0. Squaring makes every residual positive and punishes large errors more than small ones.'),
 ('h2', 'Formulas for b₁ and b₀'),
 ('p', 'The values of b₀ and b₁ that minimize SSE are:'),
 ('eq', r'$$b_1 = \frac{\sum (x_i - \bar{x})(y_i - \bar{y})}{\sum (x_i - \bar{x})^2} = r \cdot \frac{s_y}{s_x} \qquad b_0 = \bar{y} - b_1 \bar{x}$$'),
 ('p', 'where r is the correlation between x and y, and s_{x} and s_{y} are the standard deviations of x and y. Two useful facts follow from these formulas:'),
 ('ul', ['the slope b₁ always has the **same sign as r**;',
         'the regression line always passes through the point **(x̄, ȳ)**, the mean of X and the mean of Y.']),
 ('h2', 'Worked Example: Hours Studied and Exam Score'),
 ('p', 'Five students recorded how many hours they studied for an exam (x) and the score they got (y). We find the least squares line step by step (Table 4).'),
