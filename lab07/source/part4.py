 ('p', 'If the population standard deviation **σ is known**, we use the z-test formula:'),
 ('eq', r'$$z = \frac{\bar{x} - \mu_0}{\sigma / \sqrt{n}}$$'),
 ('p', 'Where:'),
 ('ul', ['x̄ = sample mean;',
         'μ_{0} = claimed population mean (from H₀);',
         'σ = population standard deviation (known);',
         'n = sample size.']),
 ('p', '**Worked-out problem 1.** A bakery claims that its loaves of bread weigh 500 g on average. From long experience, the standard deviation is σ = 12 g. A food inspector weighs a random sample of 36 loaves and finds x̄ = 496 g. Test the claim at α = 0.05.'),
 ('p', '**Step 1.** H₀: μ = 500, H₁: μ ≠ 500. The inspector checks whether the weight is different, so the test is two-tailed.'),
 ('p', '**Step 2.** α = 0.05, so the critical values are ±1.96 (Table 5).'),
 ('p', '**Step 3.** σ is known, so we use z:'),
 ('eq', r'$$z = \frac{496 - 500}{12 / \sqrt{36}} = \frac{-4}{2} = -2.00$$'),
 ('p', '**Step 4.** −2.00 < −1.96, so z falls in the left part of the rejection region. The p-value is p = 2 · P(Z < −2.00) = 2 · 0.0228 = 0.0455, which is smaller than 0.05.'),
 ('p', '**Step 5.** We reject H₀. At the 5% significance level, the data show that the average weight of the loaves is different from 500 g (it seems to be lower).'),

 ('h2', 't-Test for a Mean (σ Unknown)'),
 ('p', 'In real life, we rarely know σ. When σ is **unknown**, we estimate it with the sample standard deviation s and use the **t-distribution**, as in Lab 6. The test statistic is:'),
 ('eq', r'$$t = \frac{\bar{x} - \mu_0}{s / \sqrt{n}}, \qquad df = n - 1$$'),
 ('p', 'The critical value comes from the t-table, with df = n − 1 degrees of freedom. The t-distribution has heavier tails than the normal curve, so its critical values are a bit larger. For large samples, they are almost the same as the z critical values.'),
 ('p', '**Worked-out problem 2.** A gym advertises that its members train for more than 45 minutes per visit on average. A random sample of 16 visits gives x̄ = 48.6 minutes and s = 6 minutes. Assume that training times are approximately normal. Do the data support the gym’s claim at α = 0.05?'),
 ('p', '**Step 1.** H₀: μ ≤ 45, H₁: μ > 45. The claim “more than 45” goes into H₁, so the test is right-tailed.'),
 ('p', '**Step 2.** α = 0.05. σ is unknown, so we use t with df = 16 − 1 = 15. The t-table gives t_{0.05, 15} = 1.753.'),
 ('p', '**Step 3.** The test statistic is:'),
 ('eq', r'$$t = \frac{48.6 - 45}{6 / \sqrt{16}} = \frac{3.6}{1.5} = 2.40$$'),
 ('p', '**Step 4.** 2.40 > 1.753, so t falls in the rejection region. In Excel, =T.DIST.RT(2.4, 15) gives p ≈ 0.015, which is smaller than 0.05.'),
 ('p', '**Step 5.** We reject H₀. The data support the claim that members train for more than 45 minutes per visit on average.'),

 ('h2', 'z-Test for a Proportion'),
 ('p', 'When the claim is about a percentage, we use the **sample proportion**, where x is the number of successes and n is the sample size:'),
 ('eq', r'$$p = \frac{x}{n}$$'),
 ('p', 'In a test, we assume that H₀ is true, so the standard error of the sample proportion is calculated with the claimed value π_{0}:'),
 ('eq', r'$$\sigma_p = \sqrt{\frac{\pi_0 (1 - \pi_0)}{n}} \qquad z = \frac{p - \pi_0}{\sigma_p}$$'),
 ('p', 'We can use the normal curve if the sample is large enough:'),
 ('eq', r'$$n \cdot \pi_0 \ge 5 \qquad \text{and} \qquad n \cdot (1 - \pi_0) \ge 5$$'),
 ('box', 'mistake', '**Common mistake:** Using the sample proportion p in the standard error of a test. In a confidence interval (Lab 6) we use p, but in a hypothesis test we use the claimed value π_{0} from H₀.'),
 ('p', '**Worked-out problem 3.** A streaming service claims that 40% of its users watch something every day. The marketing team thinks that the true percentage is higher. In a random sample of 200 users, 92 watched something every day. Test at α = 0.05.'),
 ('p', '**Step 1.** H₀: π ≤ 0.40, H₁: π > 0.40 (right-tailed test).'),
 ('p', '**Step 2.** α = 0.05, so z_{0.05} = 1.645. The sample is large enough: 200 · 0.40 = 80 ≥ 5 and 200 · 0.60 = 120 ≥ 5.'),
 ('p', '**Step 3.** p = 92/200 = 0.46, and:'),
 ('eq', r'$$\sigma_p = \sqrt{\frac{0.40 \cdot 0.60}{200}} \approx 0.0346 \qquad z = \frac{0.46 - 0.40}{0.0346} \approx 1.73$$'),
 ('p', '**Step 4.** 1.73 > 1.645, so z falls in the rejection region. The p-value is p = P(Z > 1.73) ≈ 0.042, which is smaller than 0.05.'),
 ('p', '**Step 5.** We reject H₀. The data show that more than 40% of the users watch something every day.'),

